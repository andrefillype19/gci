<h1>Sobre</h1>

<p>O GCI (Guia-Certificação Institucional)
	<br>- Mantem uma memorial dos eventos e atividades complementares promovidos pelo Instituto Federal de Goiás – Câmpus Anápolis;  
	<br>- Permite que os alunos do IFG-Câmpus Anápolis controlem suas horas complementares;  
	<br>- Armazena todos os certificados, assinados digitalmente, das atividades desenvolvidas;</p>
<p> Inicialmente o GCI foi desenvolvido por duas alunas do Técnico em informática para Internet, Anna Paula Vieira Silva e Tainá Lima Fonseca.
 Após várias modificações realizadas pelo Orientador do projeto, o professor Alessandro Rodrigues e Silva, 
 o sistema foi incorporado ao GUIA, Gerenciador Unificado de Informações Acadêmicas, desenvolvido pela 4º turma de TI-Informática para Internet.
O GUIA agora é mantido pela Fábrica de Sofware Shannon, formada pelos alunos do curso de Ciência da Computação IFG Anápolis. </p>
